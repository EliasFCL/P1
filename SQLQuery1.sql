CREATE TABLE DetallesFactura (
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    numeroFactura NVARCHAR(50) NOT NULL, 
    ProductoId UNIQUEIDENTIFIER NOT NULL, 
    unidadMedida NVARCHAR(50) NOT NULL,
